"""Command line: extract | evaluate | audit | annotate."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .audit import audit_document, format_audit
from .evaluate import evaluate_pairs, format_summary, pair_files
from .export import export, read_json
from .pipeline import Config, run


def parse_pages(spec: str | None) -> tuple[int, ...] | None:
    """"3,24-26,263" -> (3, 24, 25, 26, 263) (1-based)."""
    if not spec:
        return None
    out: list[int] = []
    for part in spec.split(","):
        part = part.strip()
        if "-" in part:
            a, b = part.split("-", 1)
            out += range(int(a), int(b) + 1)
        elif part:
            out.append(int(part))
    return tuple(sorted(set(out)))


def _config(a) -> Config:
    return Config(fallback=a.fallback, dpi=a.dpi, workers=a.workers, orientation=not a.no_orientation,
                  device=a.device, pages=parse_pages(a.pages), furniture=not a.no_furniture)


def cmd_extract(a) -> int:
    formats = {f.strip() for f in a.formats.split(",") if f.strip()}
    out = Path(a.output)
    for doc in run(a.inputs, _config(a)):
        files = export(doc, out, formats)
        routes = {}
        for p in doc.pages:
            routes[p.route] = routes.get(p.route, 0) + 1
        review = sum(t.needs_review for t in doc.tables)
        print(f"{Path(doc.source).name}: {len(doc.pages)} page(s), {len(doc.tables)} table(s), "
              f"routes={routes}, needs_review={review}, {doc.meta['elapsed_s']}s -> {len(files)} file(s) in {out}")
        aud = audit_document(doc)
        if aud["total_cells_checkable"]:
            print(f"  arithmetic audit: {aud['total_cells_verified']}/{aud['total_cells_checkable']} checkable "
                  f"totals add up ({aud['verified_ratio']:.1%}); details: python main.py audit "
                  f"{out / (Path(doc.source).stem + '.json')}")
        if a.verbose:
            for p in doc.pages:
                for w in p.warnings:
                    print(f"  p{p.page}: {w}")
                for t in p.tables:
                    r = t.reliability
                    print(f"  p{p.page} t{t.index}: {t.n_rows}x{t.n_cols} header_rows={t.header_rows} "
                          f"{t.method} reliability={r.score if r else 'n/a'} unit={t.unit!r}")
    return 0


def cmd_evaluate(a) -> int:
    pairs = pair_files(Path(a.gt), Path(a.pred))
    if not pairs:
        print("no ground-truth/prediction pairs found (files are paired by name)", file=sys.stderr)
        return 2
    report = evaluate_pairs(pairs)
    print(format_summary(report))
    if a.report:
        Path(a.report).write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")
    s = report["summary"]
    return 0 if s["strict_exact_acc"] == 1.0 and s["detection"]["fp"] == 0 else 1


def cmd_audit(a) -> int:
    """Arithmetic self-consistency of extracted tables (no ground truth needed)."""
    paths = [p for x in a.inputs for p in (sorted(Path(x).rglob("*.json")) if Path(x).is_dir() else [Path(x)])]
    reports = []
    for p in paths:
        rep = audit_document(read_json(p))
        reports.append(rep)
        print(f"{p.name}:")
        print("  " + format_audit(rep, a.max_lines).replace("\n", "\n  "))
    if a.report:
        Path(a.report).write_text(json.dumps(reports, ensure_ascii=False, indent=1), encoding="utf-8")
    return 0


def cmd_annotate(a) -> int:
    """Write compact, human-editable ground-truth drafts from the current extraction.
    They must be checked against the PDF and corrected by hand before use."""
    out = Path(a.output)
    out.mkdir(parents=True, exist_ok=True)
    for doc in run(a.inputs, _config(a)):
        tables = []
        for t in doc.tables:
            tables.append({
                "page": t.page, "index": t.index, "bbox": [round(v, 1) for v in t.bbox] if t.bbox else None,
                "header_rows": t.header_rows, "title": t.title, "unit": t.unit,
                "spans": [[c.row, c.col, c.rowspan, c.colspan] for c in t.cells if c.rowspan > 1 or c.colspan > 1],
                "rows": t.matrix(),
            })
        path = out / f"{Path(doc.source).stem}.json"
        if path.exists() and not a.force:
            print(f"skip {path} (exists; use --force)")
            continue
        draft = {"source": Path(doc.source).name, "n_pages": max((p.page for p in doc.pages), default=0),
                 "verified": False,
                 "note": "DRAFT generated by the parser - verify every cell against the PDF, then set verified=true",
                 # only these pages are scored by `evaluate` (a page with no table is still annotated)
                 "annotated_pages": [p.page for p in doc.pages],
                 "tables": tables}
        path.write_text(json.dumps(draft, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"wrote {path}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="pdftable", description="Hybrid PDF-to-table parser")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def pipeline_opts(p):
        p.add_argument("inputs", nargs="+", help="PDF files or directories")
        p.add_argument("--fallback", choices=["auto", "always", "never"], default="auto",
                       help="visual fallback: only for pages failing checks (auto), every page, or never")
        p.add_argument("--dpi", type=int, default=200, help="render resolution for the visual fallback")
        p.add_argument("--workers", type=int, default=0, help="processes for native extraction (0 = CPUs)")
        p.add_argument("--pages", help="1-based pages to process, e.g. 3,24-26,263 (default: all)")
        p.add_argument("--no-orientation", action="store_true",
                       help="disable rotated-page reading frames and visual orientation correction")
        p.add_argument("--no-furniture", action="store_true",
                       help="keep running headers / footers / page numbers in the word layer")
        p.add_argument("--device", default=None, help="visual model device, e.g. cpu or gpu:0")

    p = sub.add_parser("extract", help="extract tables -> JSON (+HTML, CSV)")
    pipeline_opts(p)
    p.add_argument("-o", "--output", default="output")
    p.add_argument("--formats", default="json,html,csv,pdf",
                   help="comma-separated exports: json, html, csv, pdf")
    p.add_argument("-v", "--verbose", action="store_true")
    p.set_defaults(func=cmd_extract)

    p = sub.add_parser("evaluate", help="score predictions against ground truth")
    p.add_argument("--gt", required=True, help="ground-truth JSON file or directory")
    p.add_argument("--pred", required=True, help="prediction JSON file or directory")
    p.add_argument("--report", help="write the full JSON report here")
    p.set_defaults(func=cmd_evaluate)

    p = sub.add_parser("audit", help="check that extracted totals add up (no ground truth needed)")
    p.add_argument("inputs", nargs="+", help="extraction JSON files or directories")
    p.add_argument("--report", help="write the full JSON report here")
    p.add_argument("--max-lines", type=int, default=30, help="mismatches to list per document")
    p.set_defaults(func=cmd_audit)

    p = sub.add_parser("annotate", help="bootstrap ground-truth drafts for manual correction")
    pipeline_opts(p)
    p.add_argument("-o", "--output", default="ground_truth")
    p.add_argument("--force", action="store_true")
    p.set_defaults(func=cmd_annotate)
    return ap


def main(argv: list[str] | None = None) -> int:
    a = build_parser().parse_args(argv)
    return a.func(a)
